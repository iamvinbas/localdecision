"""Build the decision-training set for a small LocalDecision model.

    python training/build_dataset.py --out data/train --per-source 1.0

Every example is one labelled question in the evaluation JSONL format (state, questions,
labels), so the trainer renders it with exactly the prompt used at inference time and can
shuffle the option order on the fly.

Only sources with permissive licenses are used (CC-BY, CC-BY-SA, CC0, MIT, Apache-2.0), so the
resulting weights can be redistributed. Evaluation datasets are kept out on purpose:

    in-domain test      BoolQ (validation), ARC-Challenge (test)     train splits are used
    never seen          AG News, SST-5, Banking77, benchmarks/smoke-v1.jsonl
"""

from __future__ import annotations

import argparse
import json
import random
from collections import Counter
from collections.abc import Callable, Iterable, Iterator
from itertools import islice
from pathlib import Path
from typing import Any

Row = dict[str, Any]
MAX_STATE_CHARS = 2000

SOURCES_LICENSES = {
    "mnli": ("nyu-mll/multi_nli", "CC-BY-3.0 / CC-BY-SA-3.0 / MIT (per genre)"),
    "snli": ("stanfordnlp/snli", "CC-BY-SA-4.0"),
    "wanli": ("alisawuffles/WANLI", "CC-BY-4.0"),
    "boolq": ("google/boolq", "CC-BY-SA-3.0"),
    "arc": ("allenai/ai2_arc", "CC-BY-SA-4.0"),
    "csqa": ("tau/commonsense_qa", "MIT"),
    "dbpedia": ("fancyzhx/dbpedia_14", "CC-BY-SA-3.0"),
    "amazon": ("fancyzhx/amazon_polarity", "Apache-2.0"),
    "civil": ("google/civil_comments", "CC0-1.0"),
    "synthetic": ("generated by this script", "MIT (this repository)"),
}


def _load(
    name: str, config: str | None = None, split: str = "train", streaming: bool = False
) -> Any:
    from datasets import load_dataset

    return load_dataset(name, config, split=split, streaming=streaming)


def _row(source: str, family: str, state: Any, question: dict[str, Any], label: Any) -> Row | None:
    if isinstance(state, str):
        state = state.strip()
        if not state or len(state) > MAX_STATE_CHARS:
            return None
    return {
        "state": state,
        "questions": {"q": question},
        "labels": {"q": label},
        "tags": [source, family],
    }


def _take(rows: Iterable[Row | None], n: int) -> list[Row]:
    return [r for r in islice((r for r in rows if r is not None), n)]


# --------------------------------------------------------------------------- NLI

SUPPORT_NOUL = [
    'Does the state support the claim: "{h}"?',
    "Based only on the state, is it true that {h_lc}",
    "Can we conclude from the state that {h_lc}",
    "Is the following statement backed by the state? {h}",
]
SUPPORT_CHOICE = [
    'What does the state say about the claim: "{h}"?',
    "How does the state relate to this statement? {h}",
]
SUPPORT_OPTIONS = {
    "supported": "The state confirms the claim",
    "contradicted": "The state says the opposite",
    "not_stated": "The state does not say either way",
}
SUPPORT_LEVELS = ["The state contradicts it", "The state does not say", "The state supports it"]
NLI_KEYS = ["supported", "not_stated", "contradicted"]  # entailment, neutral, contradiction


def _lc(text: str) -> str:
    """'The cat sat.' -> 'the cat sat?' (keeps acronyms such as 'NASA ...')."""
    text = text.strip().rstrip(".")
    return (text if text[1:2].isupper() else text[0].lower() + text[1:]) + "?"


def nli_rows(
    source: str, examples: Iterable[tuple[str, str, int]], rng: random.Random
) -> Iterator[Row | None]:
    """label index: 0 entailment, 1 neutral, 2 contradiction."""
    for premise, hypothesis, label in examples:
        if label not in (0, 1, 2) or not hypothesis.strip():
            continue
        fmt = dict(h=hypothesis.strip(), h_lc=_lc(hypothesis))
        roll = rng.random()
        # Only 1 in 3 examples is an entailment: keep half of the others as nouls, so yes/no
        # stays balanced, and turn the rest into choice questions.
        if roll < 0.5 and (label == 0 or rng.random() < 0.5):
            q = {"type": "noul", "instructions": rng.choice(SUPPORT_NOUL).format(**fmt)}
            yield _row(source, "nli", premise, q, label == 0)
        elif roll < 0.8:
            q = {
                "type": "choice",
                "instructions": rng.choice(SUPPORT_CHOICE).format(**fmt),
                "criteria": SUPPORT_OPTIONS,
            }
            yield _row(source, "nli", premise, q, NLI_KEYS[label])
        else:
            q = {
                "type": "score",
                "instructions": f'How much does the state support the claim: "{fmt["h"]}"?',
                "criteria": SUPPORT_LEVELS,
            }
            yield _row(source, "nli", premise, q, {0: 2, 1: 1, 2: 0}[label])


def _balanced_nli(
    examples: Iterable[tuple[str, str, int]], n: int, rng: random.Random
) -> list[tuple[str, str, int]]:
    buckets: dict[int, list] = {0: [], 1: [], 2: []}
    for ex in examples:
        if ex[2] in buckets and len(buckets[ex[2]]) < n // 3 + 1:
            buckets[ex[2]].append(ex)
        if all(len(b) > n // 3 for b in buckets.values()):
            break
    out = [ex for b in buckets.values() for ex in b]
    rng.shuffle(out)
    return out


def mnli(n: int, rng: random.Random) -> list[Row]:
    ds = _load("nyu-mll/multi_nli", streaming=True).shuffle(seed=1, buffer_size=50_000)
    ex = _balanced_nli(((r["premise"], r["hypothesis"], r["label"]) for r in ds), n, rng)
    return _take(nli_rows("mnli", ex, rng), n)


def snli(n: int, rng: random.Random) -> list[Row]:
    ds = _load("stanfordnlp/snli", streaming=True).shuffle(seed=1, buffer_size=50_000)
    ex = _balanced_nli(((r["premise"], r["hypothesis"], r["label"]) for r in ds), n, rng)
    return _take(nli_rows("snli", ex, rng), n)


def wanli(n: int, rng: random.Random) -> list[Row]:
    ds = _load("alisawuffles/WANLI")
    index = {"entailment": 0, "neutral": 1, "contradiction": 2}
    ex = _balanced_nli(
        ((r["premise"], r["hypothesis"], index.get(r["gold"], -1)) for r in ds.shuffle(seed=1)),
        n,
        rng,
    )
    return _take(nli_rows("wanli", ex, rng), n)


# --------------------------------------------------------------------------- QA


def boolq(n: int, rng: random.Random) -> list[Row]:
    ds = _load("google/boolq").shuffle(seed=1)
    no = sum(1 for r in ds if not r["answer"])
    rows, yes = [], 0
    for r in ds:
        if r["answer"]:  # the dataset is ~62% "yes": keep as many yes as no
            yes += 1
            if yes > no:
                continue
        q = r["question"].strip()
        rows.append(
            _row(
                "boolq",
                "reading",
                r["passage"],
                {"type": "noul", "instructions": q[0].upper() + q[1:] + "?"},
                bool(r["answer"]),
            )
        )
    return _take(rows, n)


MCQ_INSTRUCTIONS = [
    "Which option correctly answers the question in the state?",
    "Pick the correct answer to the question.",
    "What is the right answer?",
]


def _mcq(
    source: str, question: str, texts: list[str], answer: str, rng: random.Random
) -> Row | None:
    if len(set(texts)) != len(texts) or answer not in texts:
        return None
    q = {
        "type": "choice",
        "instructions": rng.choice(MCQ_INSTRUCTIONS),
        "criteria": dict.fromkeys(texts),
    }
    return _row(source, "mcq", question, q, answer)


def arc(n: int, rng: random.Random) -> list[Row]:
    rows = []
    for config in ("ARC-Easy", "ARC-Challenge"):
        for r in _load("allenai/ai2_arc", config, split="train"):
            texts, labels = r["choices"]["text"], r["choices"]["label"]
            if r["answerKey"] in labels:
                rows.append(
                    _mcq("arc", r["question"], texts, texts[labels.index(r["answerKey"])], rng)
                )
    rng.shuffle(rows)
    return _take(rows, n)


def csqa(n: int, rng: random.Random) -> list[Row]:
    rows = []
    for r in _load("tau/commonsense_qa", split="train").shuffle(seed=1):
        texts, labels = r["choices"]["text"], r["choices"]["label"]
        if r["answerKey"] in labels:
            rows.append(
                _mcq("csqa", r["question"], texts, texts[labels.index(r["answerKey"])], rng)
            )
    return _take(rows, n)


# --------------------------------------------------------------------------- topic

DBPEDIA = {
    "Company": "A business or corporation",
    "EducationalInstitution": "A school, college or university",
    "Artist": "A musician, painter, actor or other artist",
    "Athlete": "A sports person",
    "OfficeHolder": "A politician or public official",
    "MeanOfTransportation": "A vehicle, ship, aircraft or train",
    "Building": "A building or structure",
    "NaturalPlace": "A mountain, river, lake or other natural feature",
    "Village": "A village or small settlement",
    "Animal": "An animal species",
    "Plant": "A plant species",
    "Album": "A music album",
    "Film": "A movie",
    "WrittenWork": "A book, journal or other written work",
}
TOPIC_INSTRUCTIONS = [
    "What kind of entity does the text describe?",
    "Which category fits the subject of this text?",
    "Classify the subject of the description.",
]
NONE_KEY = "none_of_these"


def dbpedia(n: int, rng: random.Random) -> list[Row]:
    ds = _load("fancyzhx/dbpedia_14", streaming=True).shuffle(seed=1, buffer_size=50_000)
    names = list(DBPEDIA)
    rows = []
    for r in islice(ds, n * 2):
        gold = names[r["label"]]
        k = rng.randint(3, len(names))
        options = [gold] + rng.sample([x for x in names if x != gold], k - 1)
        label = gold
        if rng.random() < 0.12:  # teach "none of these" when the right answer is missing
            options.remove(gold)
            options.append(NONE_KEY)
            label = NONE_KEY
        rng.shuffle(options)
        criteria = {
            o: ("None of the other options fits" if o == NONE_KEY else DBPEDIA[o]) for o in options
        }
        text = f"{r['title']}: {r['content']}"
        q = {"type": "choice", "instructions": rng.choice(TOPIC_INSTRUCTIONS), "criteria": criteria}
        rows.append(_row("dbpedia", "topic", text, q, label))
    return _take(rows, n)


# --------------------------------------------------------------------------- sentiment & moderation

POSITIVE_NOUL = [
    "Is the review positive?",
    "Is the customer satisfied with the product?",
    "Would the reviewer recommend this product?",
]


def amazon(n: int, rng: random.Random) -> list[Row]:
    ds = _load("fancyzhx/amazon_polarity", streaming=True).shuffle(seed=1, buffer_size=50_000)
    rows = []
    for r in islice(ds, n * 2):
        state = f"{r['title']}\n{r['content']}"
        if rng.random() < 0.8:
            q = {"type": "noul", "instructions": rng.choice(POSITIVE_NOUL)}
            rows.append(_row("amazon", "sentiment", state, q, r["label"] == 1))
        else:
            q = {
                "type": "choice",
                "instructions": "What is the overall sentiment of the review?",
                "criteria": {
                    "positive": "The reviewer is happy",
                    "negative": "The reviewer is unhappy",
                },
            }
            rows.append(
                _row("amazon", "sentiment", state, q, "positive" if r["label"] == 1 else "negative")
            )
    return _take(rows, n)


TOXIC_LEVELS = [
    "Not toxic: civil, even if critical",
    "Borderline: rude or dismissive",
    "Toxic: insulting or hostile",
    "Severely toxic: hateful, threatening or obscene",
]


def civil(n: int, rng: random.Random) -> list[Row]:
    """Toxicity = share of annotators who rated the comment toxic; binned into 4 levels."""
    ds = _load("google/civil_comments", streaming=True).shuffle(seed=1, buffer_size=100_000)
    edges = (0.1, 0.4, 0.7)
    quota = n // 4 + 1
    per_level: dict[int, list[Row]] = {0: [], 1: [], 2: [], 3: []}
    for r in islice(ds, 800_000):  # severe comments are rare: stop scanning eventually
        level = sum(r["toxicity"] >= e for e in edges)
        if len(per_level[level]) >= quota:
            if all(len(v) >= quota for v in per_level.values()):
                break
            continue
        if rng.random() < 0.7:
            q = {
                "type": "score",
                "instructions": "How toxic is this comment?",
                "criteria": TOXIC_LEVELS,
            }
            row = _row("civil", "moderation", r["text"], q, level)
        else:
            if 0.4 <= r["toxicity"] < 0.6:  # ambiguous for a yes/no label
                continue
            q = {
                "type": "noul",
                "instructions": rng.choice(
                    ["Is this comment toxic?", "Should a moderator remove this comment?"]
                ),
            }
            row = _row("civil", "moderation", r["text"], q, r["toxicity"] >= 0.5)
        if row:
            per_level[level].append(row)
    rows = [r for v in per_level.values() for r in v]
    rng.shuffle(rows)
    return rows[:n]


